import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import type { FastifyInstance, InjectOptions } from "fastify";
import { buildApp } from "../app";
import { hashPassword } from "../security";
import { seedDemo } from "../seed-data";
import type { VitrineState } from "@/types/api";
import type { Demand, Interest } from "@/types";

const headers = { "x-vitrine-client": "web", origin: "http://localhost:5173" };
const studentData = { name: "Estudante Teste", email: "teste@feac.ufal.br", password: "teste12345", unit: "FEAC", course: "Economia", consent: true };
const requesterData = { organization: "Organização Teste", contactName: "Responsável", email: "contato@example.com", password: "teste12345", city: "Maceió", kind: "ong", site: "" };
const demandData = { title: "Projeto de teste", description: "Uma demanda real de integração.", area: "Software", scope: "Pequeno", deadline: "2027-12-01", skills: ["React"] };
const cookieOf = (response: { headers: Record<string, unknown> }) => String(response.headers["set-cookie"]).split(";")[0];
const request = (app: FastifyInstance, method: InjectOptions["method"], url: string, payload?: object, cookie?: string) => app.inject({ method, url, payload, headers: { ...headers, ...(cookie ? { cookie } : {}) } });

async function setup(path = ":memory:") {
  const built = await buildApp({ databasePath: path, logger: false, demo: false, production: false });
  built.db.put("accounts", { id: "curator-test", email: "curator@example.com", passwordHash: await hashPassword("curator12345"), name: "Curadoria", role: "curator", profileId: "", createdAt: new Date().toISOString() });
  const student = await request(built.app, "POST", "/api/auth/students", studentData);
  assert.equal(student.statusCode, 201, student.body);
  const requester = await request(built.app, "POST", "/api/auth/requesters", requesterData);
  assert.equal(requester.statusCode, 201, requester.body);
  const curator = await request(built.app, "POST", "/api/auth/login", { email: "curator@example.com", password: "curator12345" });
  assert.equal(curator.statusCode, 200, curator.body);
  const studentId = student.json<VitrineState>().accounts[0].profileId;
  return { ...built, studentId, studentCookie: cookieOf(student), requesterCookie: cookieOf(requester), curatorCookie: cookieOf(curator) };
}

test("cadastro, autenticação, privacidade e autorização", async t => {
  const c = await setup(); t.after(() => c.app.close());
  const anon = await request(c.app, "GET", "/api/state");
  assert.equal(anon.statusCode, 200);
  assert.equal(anon.json<VitrineState>().students.length, 0);
  assert.deepEqual(anon.json<VitrineState>().accounts, []);
  assert.ok(!anon.body.includes("password"));
  assert.equal((await request(c.app, "POST", "/api/auth/students", studentData)).statusCode, 409);
  assert.equal((await request(c.app, "POST", "/api/auth/students", { ...studentData, email: "bad@evilufal.br" })).statusCode, 400);
  assert.equal((await request(c.app, "POST", "/api/auth/students", { ...studentData, email: "new@ufal.br", course: "Inexistente" })).statusCode, 400);
  assert.equal((await request(c.app, "POST", "/api/auth/students", { ...studentData, email: "new@ufal.br", role: "curator" })).statusCode, 400);
  assert.equal((await request(c.app, "POST", "/api/auth/students", { ...studentData, email: "new@ufal.br", consent: false })).statusCode, 400);
  assert.equal((await request(c.app, "POST", "/api/auth/login", { email: studentData.email, password: "wrong" })).statusCode, 401);
  assert.equal((await request(c.app, "POST", "/api/auth/login", { email: studentData.email, password: studentData.password, role: "curator" })).statusCode, 401);
  assert.equal((await request(c.app, "PATCH", `/api/students/${c.studentId}`, { skills: ["React"] })).statusCode, 401);
  assert.equal((await request(c.app, "PATCH", `/api/students/${c.studentId}`, { skills: ["React"] }, c.requesterCookie)).statusCode, 403);
  assert.equal((await request(c.app, "PATCH", `/api/students/${c.studentId}`, { email: "changed@example.com" }, c.studentCookie)).statusCode, 400);
  const profile = await request(c.app, "PATCH", `/api/students/${c.studentId}`, { skills: ["reactjs"], matricula: "123456", bio: "Meu perfil" }, c.studentCookie);
  assert.equal(profile.statusCode, 200, profile.body);
  const visible = (await request(c.app, "GET", "/api/state")).json<VitrineState>();
  assert.deepEqual(visible.students[0].skills, ["React"]);
  assert.equal(visible.students[0].email, "");
  assert.equal(visible.students[0].matricula, undefined);
  assert.equal(visible.companies[0].contactEmail, "");
  const account = c.db.all("accounts").find(a => a.role === "student")!;
  assert.ok(account.passwordHash.startsWith("scrypt:"));
  assert.ok(!JSON.stringify(account).includes(studentData.password));
  const logout = await request(c.app, "POST", "/api/auth/logout", undefined, c.studentCookie);
  assert.equal(logout.statusCode, 200);
  assert.equal((await request(c.app, "GET", "/api/auth/me", undefined, c.studentCookie)).statusCode, 401);
});

test("sugestão exige dois aceites, oculta dados e permite mensagens só depois", async t => {
  const c = await setup(); t.after(() => c.app.close());
  await request(c.app, "PATCH", `/api/students/${c.studentId}`, { skills: ["React"] }, c.studentCookie);
  const created = await request(c.app, "POST", "/api/demands", demandData, c.requesterCookie);
  assert.equal(created.statusCode, 201, created.body);
  const demand = created.json<{ demand: Demand }>().demand;
  assert.equal(demand.company, requesterData.organization);
  assert.equal((await request(c.app, "GET", "/api/state")).json<VitrineState>().demands.length, 0);
  assert.equal((await request(c.app, "PATCH", `/api/demands/${demand.id}/status`, { status: "aprovada" }, c.requesterCookie)).statusCode, 403);
  assert.equal((await request(c.app, "PATCH", `/api/demands/${demand.id}/status`, { status: "contato_liberado" }, c.curatorCookie)).statusCode, 400);
  assert.equal((await request(c.app, "PATCH", `/api/demands/${demand.id}/status`, { status: "aprovada" }, c.curatorCookie)).statusCode, 200);
  const body = { demandId: demand.id, studentId: c.studentId, origin: "sugestao", justification: "Competência compatível" };
  assert.equal((await request(c.app, "POST", "/api/interests", body, c.requesterCookie)).statusCode, 403);
  assert.equal((await request(c.app, "POST", "/api/interests", { ...body, justification: "" }, c.curatorCookie)).statusCode, 400);
  const suggested = await request(c.app, "POST", "/api/interests", body, c.curatorCookie);
  assert.equal(suggested.statusCode, 201, suggested.body);
  const interest = suggested.json<{ interest: Interest }>().interest;
  const duplicate = await request(c.app, "POST", "/api/interests", body, c.curatorCookie);
  assert.equal(duplicate.json<{ interest: Interest }>().interest.id, interest.id);
  const hiddenDuplicate = await request(c.app, "POST", "/api/interests", { ...body, origin: "convite" }, c.requesterCookie);
  assert.equal(hiddenDuplicate.statusCode, 409);
  assert.ok(!hiddenDuplicate.body.includes("Competência compatível"));
  const requesterState = (await request(c.app, "GET", "/api/state", undefined, c.requesterCookie)).json<VitrineState>();
  assert.equal(requesterState.interests.length, 0);
  assert.ok(requesterState.notifications.every(n => !n.interestId));
  assert.equal((await request(c.app, "POST", `/api/interests/${interest.id}/respond`, { accept: true }, c.curatorCookie)).statusCode, 403);
  assert.equal((await request(c.app, "POST", `/api/interests/${interest.id}/respond`, { accept: true }, c.requesterCookie)).statusCode, 409);
  const studentState = (await request(c.app, "GET", "/api/state", undefined, c.studentCookie)).json<VitrineState>();
  const notificationId = studentState.notifications[0].id;
  assert.equal((await request(c.app, "POST", `/api/notifications/${notificationId}/reply`, { content: "Olá" }, c.studentCookie)).statusCode, 409);
  const acceptedStudent = await request(c.app, "POST", `/api/interests/${interest.id}/respond`, { accept: true }, c.studentCookie);
  assert.equal(acceptedStudent.statusCode, 200, acceptedStudent.body);
  assert.equal(acceptedStudent.json<VitrineState>().interests[0].status, "aguardando_solicitante");
  assert.equal(acceptedStudent.json<VitrineState>().companies[0].contactEmail, "");
  const acceptedRequester = await request(c.app, "POST", `/api/interests/${interest.id}/respond`, { accept: true }, c.requesterCookie);
  assert.equal(acceptedRequester.statusCode, 200, acceptedRequester.body);
  assert.equal(acceptedRequester.json<VitrineState>().students[0].email, studentData.email);
  assert.equal(acceptedRequester.json<VitrineState>().demands[0].status, "contato_liberado");
  assert.equal((await request(c.app, "GET", "/api/state", undefined, c.studentCookie)).json<VitrineState>().companies[0].contactEmail, requesterData.email);
  assert.equal((await request(c.app, "POST", `/api/interests/${interest.id}/respond`, { accept: false }, c.studentCookie)).statusCode, 409);
  assert.equal((await request(c.app, "POST", `/api/notifications/${notificationId}/reply`, { content: "Olá, podemos conversar?" }, c.studentCookie)).statusCode, 200);
  const inbox = (await request(c.app, "GET", "/api/state", undefined, c.requesterCookie)).json<VitrineState>().notifications;
  assert.ok(inbox.some(n => n.content === "Olá, podemos conversar?"));
  assert.equal((await request(c.app, "POST", `/api/notifications/${inbox[0].id}/read`, undefined, c.studentCookie)).statusCode, 404);
  assert.equal((await request(c.app, "POST", "/api/notifications/read-all", undefined, c.requesterCookie)).json<VitrineState>().notifications.some(n => n.unread), false);
  assert.equal((await request(c.app, "GET", "/api/impact")).json().released, 1);
});

test("candidatura, convite, recusa privada e validação de perfil", async t => {
  const c = await setup(); t.after(() => c.app.close());
  const created = await request(c.app, "POST", "/api/demands", demandData, c.requesterCookie);
  const demand = created.json<{ demand: Demand }>().demand;
  const body = { demandId: demand.id, studentId: c.studentId, origin: "candidatura" };
  assert.equal((await request(c.app, "POST", "/api/interests", body, c.studentCookie)).statusCode, 409);
  await request(c.app, "PATCH", `/api/demands/${demand.id}/status`, { status: "aprovada" }, c.curatorCookie);
  assert.equal((await request(c.app, "POST", "/api/interests", body, c.studentCookie)).statusCode, 409);
  await request(c.app, "PATCH", `/api/students/${c.studentId}`, { skills: ["React"] }, c.studentCookie);
  const interest = (await request(c.app, "POST", "/api/interests", body, c.studentCookie)).json<{ interest: Interest }>().interest;
  assert.equal(interest.status, "aguardando_solicitante");
  assert.equal((await request(c.app, "DELETE", `/api/demands/${demand.id}`, undefined, c.curatorCookie)).statusCode, 409);
  assert.equal((await request(c.app, "PATCH", `/api/demands/${demand.id}/status`, { status: "rejeitada" }, c.curatorCookie)).statusCode, 409);
  const refused = await request(c.app, "POST", `/api/interests/${interest.id}/respond`, { accept: false, refusalReason: "Motivo reservado" }, c.requesterCookie);
  assert.equal(refused.json<VitrineState>().interests[0].refusalReason, "Motivo reservado");
  assert.ok(!(await request(c.app, "GET", "/api/state", undefined, c.studentCookie)).body.includes("Motivo reservado"));
  const invited = await request(c.app, "POST", "/api/interests", { ...body, origin: "convite" }, c.requesterCookie);
  const invitation = invited.json<{ interest: Interest }>().interest;
  assert.equal(invitation.status, "aguardando_estudante");
  assert.equal((await request(c.app, "POST", `/api/interests/${invitation.id}/respond`, { accept: true }, c.studentCookie)).json<VitrineState>().interests[0].status, "contato_liberado");
});

test("projetos, perfis e sessões sobrevivem ao reinício", async t => {
  const folder = mkdtempSync(join(tmpdir(), "vitrine-test-"));
  const path = join(folder, "db.sqlite");
  const c = await setup(path);
  const project = { title: "Portfólio", description: "Projeto persistente", status: "coding", stack: ["React"], year: "2026", area: "Software", link: "https://example.com" };
  assert.equal((await request(c.app, "POST", "/api/projects", { ...project, link: "javascript:alert(1)" }, c.studentCookie)).statusCode, 400);
  assert.equal((await request(c.app, "POST", "/api/projects", project, c.requesterCookie)).statusCode, 403);
  assert.equal((await request(c.app, "POST", "/api/projects", project, c.studentCookie)).statusCode, 201);
  await request(c.app, "PATCH", `/api/students/${c.studentId}`, { skills: ["React"], inProject: true }, c.studentCookie);
  await c.app.close();
  const reopened = await buildApp({ databasePath: path, logger: false, production: false });
  t.after(async () => {
    await reopened.app.close();
    assert.equal(dirname(folder), tmpdir());
    rmSync(folder, { recursive: true, force: true });
  });
  const state = (await request(reopened.app, "GET", "/api/auth/me", undefined, c.studentCookie)).json<VitrineState>();
  assert.equal(state.students[0].projects[0].title, "Portfólio");
  assert.equal(state.inProject[c.studentId], true);
  const publicState = (await request(reopened.app, "GET", "/api/state")).json<VitrineState>();
  assert.equal(publicState.students[0].projects.length, 1);
  assert.equal(publicState.impact.projects, 1);
});

test("CSRF, limite de login, seed explícito e cookie seguro", async t => {
  const { app, db } = await buildApp({ databasePath: ":memory:", logger: false, demo: true });
  t.after(() => app.close());
  await seedDemo(db);
  await assert.rejects(seedDemo(db), /banco vazio/);
  assert.equal((await app.inject({ method: "POST", url: "/api/auth/login", payload: {} })).statusCode, 403);
  assert.equal((await app.inject({ method: "POST", url: "/api/auth/login", payload: {}, headers: { ...headers, origin: "https://evil.example" } })).statusCode, 403);
  const login = await request(app, "POST", "/api/auth/login", { email: "estudante@ic.ufal.br", password: "demo1234" });
  assert.equal(login.statusCode, 200, login.body);
  assert.match(String(login.headers["set-cookie"]), /HttpOnly/);
  assert.match(String(login.headers["set-cookie"]), /SameSite=Strict/);
  assert.ok(!login.body.includes("password"));
  for (let n = 0; n < 11; n++) await request(app, "POST", "/api/auth/login", { email: "x@example.com", password: "wrong" });
  assert.equal((await request(app, "POST", "/api/auth/login", { email: "x@example.com", password: "wrong" })).statusCode, 429);
  assert.equal((await request(app, "POST", "/api/reset", {}, cookieOf(login))).statusCode, 404);
});
